-- REPORTE 2: Auditoria de rotacion de inventario en un rango de fechas

CREATE OR REPLACE FUNCTION sp_reporte_rotacion_inventario(
    p_fecha_inicio DATE,
    p_fecha_fin    DATE,
    p_categoria_id INT DEFAULT NULL
)
RETURNS TABLE (
    sku                      TEXT,
    producto                 TEXT,
    categoria                TEXT,
    stock_promedio           NUMERIC,
    total_salidas_unidades   BIGINT,
    valor_total_salidas_usd  NUMERIC,
    promedio_diario_salidas  NUMERIC,
    dias_inventario_restante INT,
    clasificacion_abc        TEXT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_dias  INT;
    v_total NUMERIC;
    v_filas INT;
BEGIN
    -- Validacion de parametros
    IF p_fecha_inicio IS NULL OR p_fecha_fin IS NULL THEN
        RAISE EXCEPTION 'Las fechas de inicio y fin son obligatorias. Operación cancelada.';
    END IF;
    IF p_fecha_inicio > p_fecha_fin THEN
        RAISE EXCEPTION 'La fecha de inicio (%) no puede ser posterior a la fecha fin (%). Operación cancelada.',
            p_fecha_inicio, p_fecha_fin;
    END IF;
    IF p_categoria_id IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM categorias c WHERE c.categoria_id = p_categoria_id) THEN
        RAISE EXCEPTION 'La categoría con ID % no existe. Operación cancelada.', p_categoria_id;
    END IF;

    v_dias := (p_fecha_fin - p_fecha_inicio) + 1;

    CREATE TEMP TABLE tmp_rotacion (
        t_producto_id  INT,
        t_sku          TEXT,
        t_producto     TEXT,
        t_categoria    TEXT,
        t_stock_total  NUMERIC DEFAULT 0,
        t_stock_prom   NUMERIC DEFAULT 0,
        t_salidas      NUMERIC DEFAULT 0,
        t_valor        NUMERIC(14,2) DEFAULT 0,
        t_prom_dia     NUMERIC DEFAULT 0,
        t_dias         INT DEFAULT 0,
        t_clase        TEXT
    );

    -- PASO 1: agregaciones del periodo. Stock y movimientos pasan por RLS, asi que
    -- solo se cuentan los registros autorizados para la sesion.
    INSERT INTO tmp_rotacion (t_producto_id, t_sku, t_producto, t_categoria,
                              t_stock_total, t_stock_prom, t_salidas, t_valor)
    SELECT p.producto_id, p.sku, p.nombre, c.nombre,
           COALESCE((SELECT SUM(s.cantidad) FROM stock s WHERE s.producto_id = p.producto_id), 0),
           COALESCE((SELECT AVG(s.cantidad) FROM stock s WHERE s.producto_id = p.producto_id), 0),
           COALESCE((SELECT SUM(m.cantidad)
                     FROM movimientos_inventario m
                     WHERE m.producto_id = p.producto_id
                       AND m.tipo = 'SALIDA'
                       AND m.venta_id IS NOT NULL
                       AND m.fecha >= p_fecha_inicio
                       AND m.fecha <  p_fecha_fin + 1), 0),
           COALESCE((SELECT SUM(m.cantidad * COALESCE(dv.precio_unitario, p.precio_venta))
                     FROM movimientos_inventario m
                     LEFT JOIN detalle_ventas dv
                            ON dv.venta_id = m.venta_id AND dv.producto_id = m.producto_id
                     WHERE m.producto_id = p.producto_id
                       AND m.tipo = 'SALIDA'
                       AND m.venta_id IS NOT NULL
                       AND m.fecha >= p_fecha_inicio
                       AND m.fecha <  p_fecha_fin + 1), 0)
    FROM productos p
    JOIN subcategorias sc ON sc.subcategoria_id = p.subcategoria_id
    JOIN categorias    c  ON c.categoria_id = sc.categoria_id
    WHERE (p_categoria_id IS NULL OR c.categoria_id = p_categoria_id)
      AND EXISTS (SELECT 1 FROM stock s WHERE s.producto_id = p.producto_id);

    SELECT COUNT(*), COALESCE(SUM(t.t_valor), 0)
      INTO v_filas, v_total
    FROM tmp_rotacion t;

    -- PASO 2: metricas derivadas 
    UPDATE tmp_rotacion t
    SET t_prom_dia = ROUND(t.t_salidas / v_dias, 2),
        t_dias = CASE
                    WHEN t.t_salidas = 0 THEN 9999
                    ELSE ROUND(t.t_stock_total * v_dias / t.t_salidas)::INT
                 END;

    -- PASO 3: clasificacion ABC segun el porcentaje del valor total de salidas
    UPDATE tmp_rotacion t
    SET t_clase = CASE
            WHEN v_total <= 0                      THEN 'Clase C (Baja Rotación)'
            WHEN t.t_valor / v_total * 100 >= 50   THEN 'Clase A (Alta Rotación)'
            WHEN t.t_valor / v_total * 100 >= 10   THEN 'Clase B (Rotación Media)'
            ELSE 'Clase C (Baja Rotación)'
        END;

    -- Registro del reporte generado
    INSERT INTO bitacora_reportes (reporte, fecha_inicio, fecha_fin, categoria_id, usuario, filas_generadas)
    VALUES ('sp_reporte_rotacion_inventario', p_fecha_inicio, p_fecha_fin,
            p_categoria_id, current_user, v_filas);

    RETURN QUERY
    SELECT t.t_sku::TEXT, t.t_producto::TEXT, t.t_categoria::TEXT,
           ROUND(t.t_stock_prom, 1),
           t.t_salidas::BIGINT,
           t.t_valor,
           t.t_prom_dia,
           t.t_dias,
           t.t_clase::TEXT
    FROM tmp_rotacion t
    ORDER BY t.t_valor DESC, t.t_sku;

    DROP TABLE tmp_rotacion;

EXCEPTION
    WHEN raise_exception THEN
        RAISE;   -- errores de validacion propios: se propagan tal cual
    WHEN OTHERS THEN
        RAISE EXCEPTION 'Error inesperado en sp_reporte_rotacion_inventario: %', SQLERRM;
END;
$$;

-- RUTINA 1: Procesamiento de venta y despacho 
CREATE OR REPLACE FUNCTION sp_procesar_venta(
    p_almacen_id INT,
    p_productos  INT[],
    p_cantidades INT[]
)
RETURNS INT
LANGUAGE plpgsql
AS $$
DECLARE
    v_venta_id INT;
    v_i        INT;
    v_stock    INT;
    v_precio   NUMERIC(12,2);
BEGIN
    -- Validacion de parametros
    IF p_almacen_id IS NULL OR p_productos IS NULL OR p_cantidades IS NULL THEN
        RAISE EXCEPTION 'Parámetros incompletos: almacén, productos y cantidades son obligatorios. Operación cancelada.';
    END IF;
    IF COALESCE(array_length(p_productos, 1), 0) = 0
       OR array_length(p_productos, 1) <> COALESCE(array_length(p_cantidades, 1), 0) THEN
        RAISE EXCEPTION 'La lista de productos y la de cantidades deben tener la misma longitud y no estar vacías. Operación cancelada.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM almacenes a WHERE a.almacen_id = p_almacen_id) THEN
        RAISE EXCEPTION 'El almacén con ID % no existe. Operación cancelada.', p_almacen_id;
    END IF;
    IF NOT fn_puede_ver_almacen(p_almacen_id) THEN
        RAISE EXCEPTION 'No tiene autoridad sobre el almacén %. Operación cancelada.', p_almacen_id;
    END IF;

    -- PASO 1: validacion previa de stock de TODOS los productos 
    FOR v_i IN 1 .. array_length(p_productos, 1) LOOP
        IF p_cantidades[v_i] IS NULL OR p_cantidades[v_i] <= 0 THEN
            RAISE EXCEPTION 'La cantidad del producto % debe ser mayor que cero. Operación cancelada.', p_productos[v_i];
        END IF;

        SELECT s.cantidad INTO v_stock
        FROM stock s
        WHERE s.almacen_id = p_almacen_id AND s.producto_id = p_productos[v_i];

        IF NOT FOUND THEN
            RAISE EXCEPTION 'El producto % no tiene existencias registradas en el almacén %. Venta revertida.',
                p_productos[v_i], p_almacen_id;
        END IF;

        IF v_stock < p_cantidades[v_i] THEN
            RAISE EXCEPTION 'Stock insuficiente del producto % en el almacén % (disponible: %, solicitado: %). Venta revertida.',
                p_productos[v_i], p_almacen_id, v_stock, p_cantidades[v_i];
        END IF;
    END LOOP;

    -- PASO 2: cabecera del pedido
    INSERT INTO ventas (almacen_id) VALUES (p_almacen_id)
    RETURNING venta_id INTO v_venta_id;

    -- PASOS 3, 4 y 5: detalle, descuento de existencias y auditoria de movimientos
    FOR v_i IN 1 .. array_length(p_productos, 1) LOOP
        SELECT p.precio_venta INTO v_precio
        FROM productos p WHERE p.producto_id = p_productos[v_i];

        INSERT INTO detalle_ventas (venta_id, producto_id, cantidad, precio_unitario)
        VALUES (v_venta_id, p_productos[v_i], p_cantidades[v_i], v_precio);

        UPDATE stock s
        SET cantidad = s.cantidad - p_cantidades[v_i]
        WHERE s.almacen_id = p_almacen_id AND s.producto_id = p_productos[v_i];

        INSERT INTO movimientos_inventario (producto_id, almacen_id, tipo, cantidad, venta_id)
        VALUES (p_productos[v_i], p_almacen_id, 'SALIDA', p_cantidades[v_i], v_venta_id);
    END LOOP;

    RAISE NOTICE 'Venta % registrada correctamente en el almacén %.', v_venta_id, p_almacen_id;
    RETURN v_venta_id;

EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE 'ROLLBACK automático de la venta: %', SQLERRM;
        RAISE;
END;
$$;

-- RUTINA 2: Transferencia de inventario entre almacenes

CREATE OR REPLACE FUNCTION sp_transferir_inventario(
    p_origen      INT,
    p_destino     INT,
    p_producto_id INT,
    p_cantidad    INT
)
RETURNS INT
LANGUAGE plpgsql
AS $$
DECLARE
    v_transf_id INT;
    v_stock     INT;
BEGIN
    -- Validacion de parametros
    IF p_origen IS NULL OR p_destino IS NULL OR p_producto_id IS NULL OR p_cantidad IS NULL THEN
        RAISE EXCEPTION 'Parámetros incompletos para la transferencia. Operación cancelada.';
    END IF;
    IF p_origen = p_destino THEN
        RAISE EXCEPTION 'El almacén origen y el destino deben ser distintos. Operación cancelada.';
    END IF;
    IF p_cantidad <= 0 THEN
        RAISE EXCEPTION 'La cantidad a transferir debe ser mayor que cero. Operación cancelada.';
    END IF;
    IF (SELECT COUNT(*) FROM almacenes a WHERE a.almacen_id IN (p_origen, p_destino)) <> 2 THEN
        RAISE EXCEPTION 'Alguno de los almacenes indicados (origen %, destino %) no existe. Operación cancelada.',
            p_origen, p_destino;
    END IF;
    IF NOT (fn_puede_ver_almacen(p_origen) AND fn_puede_ver_almacen(p_destino)) THEN
        RAISE EXCEPTION 'No tiene autoridad sobre ambos almacenes (origen % y destino %). Operación cancelada.',
            p_origen, p_destino;
    END IF;

    -- PASO 1: validacion de origen 
    SELECT s.cantidad INTO v_stock
    FROM stock s
    WHERE s.almacen_id = p_origen AND s.producto_id = p_producto_id;

    IF NOT FOUND OR v_stock < p_cantidad THEN
        RAISE EXCEPTION 'Stock insuficiente en el almacén origen % para el producto % (disponible: %, solicitado: %). Transferencia revertida.',
            p_origen, p_producto_id, COALESCE(v_stock, 0), p_cantidad;
    END IF;

    -- PASO 2: registro de la transferencia
    INSERT INTO transferencias (almacen_origen, almacen_destino)
    VALUES (p_origen, p_destino)
    RETURNING transferencia_id INTO v_transf_id;

    INSERT INTO detalle_transferencias (transferencia_id, producto_id, cantidad)
    VALUES (v_transf_id, p_producto_id, p_cantidad);

    -- PASO 3: salida en origen
    UPDATE stock s
    SET cantidad = s.cantidad - p_cantidad
    WHERE s.almacen_id = p_origen AND s.producto_id = p_producto_id;

    -- PASO 4: entrada en destino 
    IF EXISTS (SELECT 1 FROM stock s WHERE s.almacen_id = p_destino AND s.producto_id = p_producto_id) THEN
        UPDATE stock s
        SET cantidad = s.cantidad + p_cantidad
        WHERE s.almacen_id = p_destino AND s.producto_id = p_producto_id;
    ELSE
        INSERT INTO stock (almacen_id, producto_id, cantidad)
        VALUES (p_destino, p_producto_id, p_cantidad);
    END IF;

    -- PASO 5: doble registro de auditoria 
    INSERT INTO movimientos_inventario (producto_id, almacen_id, tipo, cantidad, transferencia_id)
    VALUES (p_producto_id, p_origen, 'SALIDA', p_cantidad, v_transf_id);

    INSERT INTO movimientos_inventario (producto_id, almacen_id, tipo, cantidad, transferencia_id)
    VALUES (p_producto_id, p_destino, 'ENTRADA', p_cantidad, v_transf_id);

    RAISE NOTICE 'Transferencia % completada: % unidades del producto % de almacén % a almacén %.',
        v_transf_id, p_cantidad, p_producto_id, p_origen, p_destino;
    RETURN v_transf_id;

EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE 'ROLLBACK automático de la transferencia: %', SQLERRM;
        RAISE;
END;
$$;


