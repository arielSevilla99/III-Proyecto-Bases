-- Los roles son globales en PostgreSQL ,
-- por eso se eliminan y se recrean aqui. Primero los usuarios y luego los grupos.
DO $$
DECLARE
    v_rol TEXT;
BEGIN
    FOREACH v_rol IN ARRAY ARRAY['rol_temporal_prueba', 'rol_no_autorizado',
        'admin_test', 'gestor_norte', 'gestor_central', 'auditor_test', 'operativo_test',
        'inventory_manager', 'auditor', 'operativo', 'db_admin']
    LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = v_rol) THEN
            EXECUTE format('DROP OWNED BY %I', v_rol);
            EXECUTE format('DROP ROLE %I', v_rol);
        END IF;
    END LOOP;
END $$;


-- SECCION 1: ESQUEMA NORMALIZADO (3FNBC)



CREATE TABLE categorias (
    categoria_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE subcategorias (
    subcategoria_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id    INT NOT NULL REFERENCES categorias (categoria_id),
    nombre          VARCHAR(60) NOT NULL,
    CONSTRAINT uq_subcategoria UNIQUE (categoria_id, nombre)
);

CREATE TABLE proveedores (
    proveedor_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL UNIQUE,
    contacto      VARCHAR(100) NOT NULL,
    telefono      VARCHAR(20)  NOT NULL,
    pais          VARCHAR(60)  NOT NULL
);

CREATE TABLE almacenes (
    almacen_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(80)  NOT NULL UNIQUE,
    ubicacion   VARCHAR(100) NOT NULL
);

CREATE TABLE productos (
    producto_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(20)  NOT NULL UNIQUE,
    nombre           VARCHAR(120) NOT NULL,
    subcategoria_id  INT NOT NULL REFERENCES subcategorias (subcategoria_id),
    proveedor_id     INT NOT NULL REFERENCES proveedores (proveedor_id),
    costo_unitario   NUMERIC(12,2) NOT NULL CHECK (costo_unitario >= 0),
    precio_venta     NUMERIC(12,2) NOT NULL CHECK (precio_venta >= 0)
);

-- Pasillo, estante y niveles de stock dependen del producto EN un almacen,
-- por eso viven aqui y no en productos ni en almacenes.
CREATE TABLE stock (
    almacen_id    INT NOT NULL REFERENCES almacenes (almacen_id),
    producto_id   INT NOT NULL REFERENCES productos (producto_id),
    cantidad      INT NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    stock_minimo  INT NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    stock_optimo  INT NOT NULL DEFAULT 0,
    pasillo       VARCHAR(5),
    estante       VARCHAR(5),
    PRIMARY KEY (almacen_id, producto_id),
    CONSTRAINT ck_stock_optimo CHECK (stock_optimo >= stock_minimo)
);

CREATE TABLE ventas (
    venta_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    almacen_id  INT NOT NULL REFERENCES almacenes (almacen_id),
    fecha       TIMESTAMP NOT NULL DEFAULT now(),
    usuario     TEXT NOT NULL DEFAULT current_user
);

CREATE TABLE detalle_ventas (
    venta_id         INT NOT NULL REFERENCES ventas (venta_id),
    producto_id      INT NOT NULL REFERENCES productos (producto_id),
    cantidad         INT NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
    PRIMARY KEY (venta_id, producto_id)
);

CREATE TABLE transferencias (
    transferencia_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    almacen_origen    INT NOT NULL REFERENCES almacenes (almacen_id),
    almacen_destino   INT NOT NULL REFERENCES almacenes (almacen_id),
    fecha             TIMESTAMP NOT NULL DEFAULT now(),
    usuario           TEXT NOT NULL DEFAULT current_user,
    CONSTRAINT ck_transferencia_distintos CHECK (almacen_origen <> almacen_destino)
);

CREATE TABLE detalle_transferencias (
    transferencia_id  INT NOT NULL REFERENCES transferencias (transferencia_id),
    producto_id       INT NOT NULL REFERENCES productos (producto_id),
    cantidad          INT NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (transferencia_id, producto_id)
);

CREATE TABLE movimientos_inventario (
    movimiento_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id       INT NOT NULL REFERENCES productos (producto_id),
    almacen_id        INT NOT NULL REFERENCES almacenes (almacen_id),
    tipo              VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    cantidad          INT NOT NULL CHECK (cantidad > 0),
    fecha             TIMESTAMP NOT NULL DEFAULT now(),
    usuario           TEXT NOT NULL DEFAULT current_user,
    venta_id          INT REFERENCES ventas (venta_id),
    transferencia_id  INT REFERENCES transferencias (transferencia_id),
    CONSTRAINT ck_movimiento_origen CHECK (venta_id IS NULL OR transferencia_id IS NULL)
);

-- Tabla de apoyo para RLS: que almacen le toca a cada usuario de base de datos.
CREATE TABLE usuario_almacen (
    usuario     TEXT NOT NULL,
    almacen_id  INT NOT NULL REFERENCES almacenes (almacen_id),
    PRIMARY KEY (usuario, almacen_id)
);

-- Bitacora opcional de reportes generados (la llena sp_reporte_rotacion_inventario).
CREATE TABLE bitacora_reportes (
    bitacora_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte           VARCHAR(60) NOT NULL,
    fecha_inicio      DATE NOT NULL,
    fecha_fin         DATE NOT NULL,
    categoria_id      INT REFERENCES categorias (categoria_id),
    usuario           TEXT NOT NULL,
    fecha_generacion  TIMESTAMP NOT NULL DEFAULT now(),
    filas_generadas   INT NOT NULL DEFAULT 0
);

-- Indices para los reportes y las consultas por almacen
CREATE INDEX idx_mov_producto_fecha ON movimientos_inventario (producto_id, tipo, fecha);
CREATE INDEX idx_mov_almacen        ON movimientos_inventario (almacen_id);
CREATE INDEX idx_stock_producto     ON stock (producto_id);


 
