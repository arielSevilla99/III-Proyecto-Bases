CREATE OR REPLACE FUNCTION fn_puede_ver_almacen(p_almacen_id INT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT pg_has_role(current_user, 'db_admin', 'member')
        OR pg_has_role(current_user, 'auditor', 'member')
        OR EXISTS (
            SELECT 1
            FROM usuario_almacen ua
            WHERE ua.usuario = current_user::TEXT
              AND ua.almacen_id = p_almacen_id
        );
$$;

