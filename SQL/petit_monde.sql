-- REPORTE 1: Valoracion de inventario con proyeccion de reabastecimiento

CREATE OR REPLACE FUNCTION sp_reporte_valoracion_reabastecimiento(
    p_almacen_id    INT     DEFAULT NULL,
    p_margen_alerta NUMERIC DEFAULT 0
)
RETURNS TABLE (
    almacen                  TEXT,
    sku                      TEXT,
    producto                 TEXT,
    categoria                TEXT,
    stock_actual             INT,
    stock_minimo             INT,
    stock_optimo             INT,
    stock_promedio           NUMERIC,
    unidades_salida          BIGINT,
    costo_unitario_usd       NUMERIC,
    valor_inventario_usd     NUMERIC,
    valor_total_almacen_usd  NUMERIC,
    estado_criticidad        TEXT,
    cantidad_a_pedir         INT,
    costo_reposicion_usd     NUMERIC
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_margen NUMERIC;
    v_filas  INT;
BEGIN
    -- Validacion de parametros
    v_margen := COALESCE(p_margen_alerta, 0);
    IF v_margen < 0 OR v_margen > 100 THEN
        RAISE EXCEPTION 'El margen de alerta (%) debe estar entre 0 y 100. Operación cancelada.', v_margen;
    END IF;
    IF p_almacen_id IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM almacenes a WHERE a.almacen_id = p_almacen_id) THEN
        RAISE EXCEPTION 'El almacén con ID % no existe. Operación cancelada.', p_almacen_id;
    END IF;

    -- Tabla temporal de trabajo 
    CREATE TEMP TABLE tmp_valoracion (
        t_almacen_id  INT,
        t_almacen     TEXT,
        t_sku         TEXT,
        t_producto    TEXT,
        t_categoria   TEXT,
        t_cantidad    INT,
        t_minimo      INT,
        t_optimo      INT,
        t_prom        NUMERIC DEFAULT 0,
        t_salidas     BIGINT DEFAULT 0,
        t_costo       NUMERIC(12,2),
        t_valor       NUMERIC(14,2),
        t_valor_alm   NUMERIC(14,2) DEFAULT 0,
        t_estado      TEXT,
        t_prioridad   INT,
        t_pedir       INT DEFAULT 0,
        t_costo_rep   NUMERIC(14,2) DEFAULT 0
    );

    -- PASO 1: cargar existencias 
    INSERT INTO tmp_valoracion (t_almacen_id, t_almacen, t_sku, t_producto, t_categoria,
                                t_cantidad, t_minimo, t_optimo, t_costo, t_valor)
    SELECT a.almacen_id, a.nombre, p.sku, p.nombre, c.nombre,
           s.cantidad, s.stock_minimo, s.stock_optimo, p.costo_unitario,
           COALESCE(s.cantidad * p.costo_unitario, 0)
    FROM stock s
    JOIN almacenes     a  ON a.almacen_id = s.almacen_id
    JOIN productos     p  ON p.producto_id = s.producto_id
    JOIN subcategorias sc ON sc.subcategoria_id = p.subcategoria_id
    JOIN categorias    c  ON c.categoria_id = sc.categoria_id
    WHERE p_almacen_id IS NULL OR s.almacen_id = p_almacen_id;

    SELECT COUNT(*) INTO v_filas FROM tmp_valoracion;

    IF v_filas = 0 THEN
        RAISE NOTICE 'Sin existencias visibles para los parámetros indicados (almacén: %).', COALESCE(p_almacen_id::TEXT, 'todos');
    END IF;

    -- PASO 1b: stock promedio y unidades de salida por ventas
    UPDATE tmp_valoracion t
    SET t_prom = COALESCE((SELECT ROUND(AVG(s.cantidad), 1)
                           FROM stock s
                           JOIN productos p ON p.producto_id = s.producto_id
                           WHERE p.sku = t.t_sku), 0),
        t_salidas = COALESCE((SELECT SUM(m.cantidad)
                              FROM movimientos_inventario m
                              JOIN productos p ON p.producto_id = m.producto_id
                              WHERE p.sku = t.t_sku
                                AND m.almacen_id = t.t_almacen_id
                                AND m.tipo = 'SALIDA'
                                AND m.venta_id IS NOT NULL), 0);

    -- PASO 2: estado de criticidad, cantidad a pedir y costo de reposicion
    UPDATE tmp_valoracion t
    SET t_estado = CASE
            WHEN t.t_cantidad = 0                                   THEN 'Agotado'
            WHEN t.t_cantidad <= t.t_minimo                         THEN 'Crítico'
            WHEN t.t_cantidad <= t.t_minimo * (1 + v_margen / 100)  THEN 'En Alerta'
            ELSE 'Óptimo'
        END;

    UPDATE tmp_valoracion t
    SET t_prioridad = CASE t.t_estado
            WHEN 'Agotado'   THEN 1
            WHEN 'Crítico'   THEN 2
            WHEN 'En Alerta' THEN 3
            ELSE 4
        END,
        t_pedir = CASE
            WHEN t.t_estado <> 'Óptimo' THEN GREATEST(t.t_optimo - t.t_cantidad, 0)
            ELSE 0
        END;

    UPDATE tmp_valoracion t
    SET t_costo_rep = COALESCE(t.t_pedir * t.t_costo, 0);

    -- PASO 3: valor total del inventario por almacen
    UPDATE tmp_valoracion t
    SET t_valor_alm = x.total
    FROM (
        SELECT g.t_almacen_id, COALESCE(SUM(g.t_valor), 0) AS total
        FROM tmp_valoracion g
        GROUP BY g.t_almacen_id
    ) x
    WHERE x.t_almacen_id = t.t_almacen_id;

    -- Resultado ordenado por prioridad de abastecimiento
    RETURN QUERY
    SELECT t.t_almacen::TEXT, t.t_sku::TEXT, t.t_producto::TEXT, t.t_categoria::TEXT,
           t.t_cantidad, t.t_minimo, t.t_optimo,
           t.t_prom, t.t_salidas,
           t.t_costo, t.t_valor, t.t_valor_alm,
           t.t_estado::TEXT, t.t_pedir, t.t_costo_rep
