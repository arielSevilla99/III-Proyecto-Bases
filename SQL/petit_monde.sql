CREATE POLICY pol_stock_almacen ON stock
    FOR ALL
    USING (fn_puede_ver_almacen(almacen_id))
    WITH CHECK (fn_puede_ver_almacen(almacen_id));

CREATE POLICY pol_movimientos_almacen ON movimientos_inventario
    FOR ALL
    USING (fn_puede_ver_almacen(almacen_id))
    WITH CHECK (fn_puede_ver_almacen(almacen_id));

CREATE POLICY pol_ventas_almacen ON ventas
    FOR ALL
    USING (fn_puede_ver_almacen(almacen_id))
    WITH CHECK (fn_puede_ver_almacen(almacen_id));

-- El detalle hereda la visibilidad de su cabecera 
CREATE POLICY pol_detalle_ventas ON detalle_ventas
    FOR ALL
    USING (EXISTS (SELECT 1 FROM ventas v WHERE v.venta_id = detalle_ventas.venta_id))
    WITH CHECK (EXISTS (SELECT 1 FROM ventas v WHERE v.venta_id = detalle_ventas.venta_id));


CREATE POLICY pol_transferencias ON transferencias
    FOR ALL
    USING (fn_puede_ver_almacen(almacen_origen) OR fn_puede_ver_almacen(almacen_destino))
    WITH CHECK (fn_puede_ver_almacen(almacen_origen) AND fn_puede_ver_almacen(almacen_destino));

CREATE POLICY pol_detalle_transferencias ON detalle_transferencias
    FOR ALL
    USING (EXISTS (SELECT 1 FROM transferencias t WHERE t.transferencia_id = detalle_transferencias.transferencia_id))
    WITH CHECK (EXISTS (SELECT 1 FROM transferencias t WHERE t.transferencia_id = detalle_transferencias.transferencia_id));



